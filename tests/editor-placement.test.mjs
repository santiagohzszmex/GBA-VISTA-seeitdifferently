import assert from 'node:assert/strict';
import { placeEditorMenu } from '../src/workspace/editorPlacement.js';
import { readRecovery,writeRecovery } from '../src/workspace/draftRecovery.js';
const bounds={left:0,top:0,right:400,bottom:600},size={width:290,height:300};
assert.equal(placeEditorMenu({left:60,right:60,top:80,bottom:100},size,bounds).side,'below');
const above=placeEditorMenu({left:380,right:380,top:560,bottom:580},size,bounds);
assert.equal(above.side,'above');assert.ok(above.left>=8&&above.left+above.maxWidth<=392);assert.ok(above.top+above.maxHeight<560);
assert.equal(placeEditorMenu({left:60,right:60,top:-30,bottom:-10},size,bounds),null);
assert.equal(placeEditorMenu({left:60,right:60,top:650,bottom:670},size,bounds),null);
assert.equal(placeEditorMenu({left:60,right:60,top:20,bottom:30},size,{...bounds,bottom:70}),null);
const compact=placeEditorMenu({left:150,right:150,top:170,bottom:190},size,{...bounds,right:220,bottom:250});
assert.equal(compact.side,'above');assert.ok(compact.maxWidth<=204&&compact.maxHeight<=154);
const storage=new Map();storage.setItem=storage.set.bind(storage);storage.getItem=storage.get.bind(storage);
const payload={content_document:{type:'doc',attrs:{schemaVersion:2},content:[]},title:'Preguntas',palette:['#123456']};
writeRecovery('author','support:document',payload,3,0,storage);
assert.deepEqual(readRecovery('author','support:document',storage).payload,payload);
assert.equal(readRecovery('other','support:document',storage),null);
assert.equal(readRecovery('author','support:document',storage,Date.now()+86400001),null);
console.log('PASS: menu placement at edges, clipping, compact viewport and isolated document recovery.');
